# Deploy Bedrock Invocation Analytics
# Usage:
#   ./deploy.sh hub [cdk-options]         Deploy primary account stack
#   ./deploy.sh spoke [profile]           Deploy spoke stack(s)
#   ./deploy.sh all                       Deploy hub + all spokes
#   ./deploy.sh [cdk-command]             Raw CDK command (diff, synth, destroy, etc.)
#
# Configuration: config.yaml. CDK_REQUIRE_APPROVAL (default: broadening) controls the IAM/security-change prompt.

set -euo pipefail
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
CONFIG="$SCRIPT_DIR/config.yaml"
ENV_FILE="$SCRIPT_DIR/.env.deploy"
APPROVAL="${CDK_REQUIRE_APPROVAL:-broadening}"

if [[ ! -f "$CONFIG" ]]; then
    echo "Error: config.yaml not found"
    exit 1
fi
chmod 600 "$CONFIG"

# Every value is shell-quoted, so config content can't inject commands into the eval.
eval "$(python3 - "$CONFIG" <<'PY'
import shlex, sys, yaml
c = yaml.safe_load(open(sys.argv[1], encoding="utf-8"))
primary = next(a for a in c["accounts"] if a.get("primary"))
spokes = [a for a in c["accounts"] if not a.get("primary")]
data = c.get("data") or {}
values = {
    "PRIMARY_PROFILE": primary["profile"],
    "PRIMARY_REGION": primary["region"],
    "PRIMARY_BUCKET": primary.get("bucket") or "",
    "LOG_PREFIX": data.get("bedrock_log_prefix", "bedrock/invocation-logs/"),
    "SPOKE_LIST": "|".join(f'{a["profile"]}:{a["region"]}:{a.get("bucket") or ""}' for a in spokes),
}
for k, v in values.items():
    print(f"{k}={shlex.quote(str(v))}")
PY
)"

get_account_id() {
    aws sts get-caller-identity --profile "$1" --query Account --output text 2>/dev/null
}

run_cdk() {
    local profile="$1"; shift
    local region="$1"; shift
    (export AWS_DEFAULT_REGION="$region"; cd "$SCRIPT_DIR/deploy" && uv run --project .. cdk "$@" --profile "$profile")
}

ensure_bootstrap() {
    if ! aws cloudformation describe-stacks --profile "$1" --region "$2" --stack-name CDKToolkit &>/dev/null; then
        echo "=== Bootstrapping CDK ($1 / $2) ==="
        run_cdk "$1" "$2" bootstrap
    fi
}

write_env_file() {
    (
        umask 077
        echo "# Auto-generated by deploy.sh"
        for kv in \
            "PRIMARY_PROFILE=${PRIMARY_PROFILE}" \
            "PRIMARY_REGION=${PRIMARY_REGION}" \
            "HUB_ACCOUNT=${HUB_ACCOUNT}"; do
            printf '%s=%q\n' "${kv%%=*}" "${kv#*=}"
        done
    ) > "$ENV_FILE"
    chmod 600 "$ENV_FILE"
}

build_webui() {
    echo "=== Building WebUI ==="
    "$SCRIPT_DIR/scripts/build_webui.sh"
}

CMD="${1:-}"
shift || true

case "$CMD" in
    hub)
        echo "=== Deploying Hub (${PRIMARY_PROFILE} / ${PRIMARY_REGION}) ==="
        HUB_ACCOUNT=$(get_account_id "$PRIMARY_PROFILE")
        ensure_bootstrap "$PRIMARY_PROFILE" "$PRIMARY_REGION"
        build_webui

        PARAMS=(--parameters "LogPrefix=${LOG_PREFIX}")
        [[ -n "$PRIMARY_BUCKET" ]] && PARAMS+=(--parameters "ExistingBucketName=${PRIMARY_BUCKET}")

        run_cdk "$PRIMARY_PROFILE" "$PRIMARY_REGION" deploy BedrockInvocationAnalytics \
            -c target=hub "${PARAMS[@]}" --require-approval "$APPROVAL" "$@"
        write_env_file
        echo "=== Hub deployed. Open the WebUiUrl output above; config saved to .env.deploy ==="
        ;;

    spoke)
        TARGET_PROFILE="${1:-}"
        [[ $# -gt 0 ]] && shift
        HUB_ACCOUNT=$(get_account_id "$PRIMARY_PROFILE")
        IFS='|' read -ra SPOKES <<< "$SPOKE_LIST"
        for spoke_info in "${SPOKES[@]}"; do
            IFS=: read -r profile region bucket <<< "$spoke_info"
            [[ -n "$TARGET_PROFILE" && "$profile" != "$TARGET_PROFILE" ]] && continue
            ensure_bootstrap "$profile" "$region"

            STACK_ID="BedrockAnalytics-Spoke-${profile}-${region}"
            echo "=== Deploying Spoke (${profile} / ${region}) ==="
            PARAMS=(--parameters "${STACK_ID}:LogPrefix=${LOG_PREFIX}")
            [[ -n "$bucket" ]] && PARAMS+=(--parameters "${STACK_ID}:ExistingBucketName=${bucket}")

            run_cdk "$profile" "$region" deploy "$STACK_ID" \
                -c target="spoke:${profile}" -c hub_account="$HUB_ACCOUNT" \
                "${PARAMS[@]}" --require-approval "$APPROVAL" "$@"
            echo "=== Spoke ${profile}/${region} deployed ==="
        done
        ;;

    all)
        "$SCRIPT_DIR/deploy.sh" hub "$@"
        "$SCRIPT_DIR/deploy.sh" spoke "" "$@"
        ;;

    "")
        sed -n '5,10p' "$0"
        exit 1
        ;;

    *)
        build_webui
        run_cdk "$PRIMARY_PROFILE" "$PRIMARY_REGION" "$CMD" -c target=hub "$@"
        ;;
esac
